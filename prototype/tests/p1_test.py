from playwright.sync_api import sync_playwright
U="file:///home/claude/meridian/dist/meridian-app.html"
with sync_playwright() as p:
    b=p.chromium.launch()
    ctx=b.new_context(viewport={"width":390,"height":844},device_scale_factor=2,color_scheme="light")
    pg=ctx.new_page()
    errs=[];pg.on("pageerror",lambda e:errs.append(str(e)))
    pg.goto(U,wait_until="domcontentloaded");pg.wait_for_timeout(500)
    on=lambda:pg.evaluate("[...document.querySelectorAll('.view.on')].map(v=>v.id).join()")
    ov=lambda l:print(l,"|",on(),"| nav hidden:",pg.evaluate("document.getElementById('nav').hidden"),"| ovx:",pg.evaluate("document.documentElement.scrollWidth - window.innerWidth"))
    pg.click("#v-onboarding [data-i=ol]"); ov("home")
    print("bell dot visible:",pg.evaluate("!document.querySelector('#v-home .dotu').hidden"))
    # notifications
    pg.click("#v-home .bell"); pg.wait_for_timeout(100); pg.screenshot(path="p1-notif-loading.png")
    pg.wait_for_timeout(600); ov("notifs"); pg.screenshot(path="p1-notifs.png")
    print("unread rows:",pg.evaluate("document.querySelectorAll('#v-notifs .nr.u').length"))
    pg.click("#v-notifs .nr >> nth=0"); pg.wait_for_timeout(700); ov("notif->deal")
    print("deal title:",pg.inner_text("#v-deal h1")); pg.screenshot(path="p1-deal-aya.png")
    pg.click("#v-deal .chip >> nth=3"); print("cta:",pg.inner_text("#v-deal .go"))
    pg.click("#v-deal .back"); pg.wait_for_timeout(600); ov("back to notifs")
    print("unread after open:",pg.evaluate("document.querySelectorAll('#v-notifs .nr.u').length"))
    pg.click("#v-notifs .mar"); pg.wait_for_timeout(600)
    print("dot hidden after mark all:",pg.evaluate("document.querySelector('#v-home .dotu').hidden"),"| mar disabled:",pg.is_disabled("#v-notifs .mar"))
    # capital landing
    pg.click("#nav [data-go=capital]"); pg.wait_for_timeout(100); pg.screenshot(path="p1-cap-loading.png"); pg.wait_for_timeout(700)
    ov("capital landing"); pg.screenshot(path="p1-capital.png")
    print("rows:",pg.evaluate("document.querySelectorAll('#v-capital .rd').length"))
    pg.click("#v-capital .fc[data-f=soon]"); print("closing soon:",pg.evaluate("document.querySelectorAll('#v-capital .rd').length"))
    pg.click("#v-capital .fc[data-f=new]"); print("new:",pg.evaluate("[...document.querySelectorAll('#v-capital .rd b')].map(x=>x.textContent)"))
    pg.click("#v-capital .fc[data-f=closed]"); pg.wait_for_timeout(100); print("closed empty:",pg.inner_text("#v-capital .es h3")); pg.screenshot(path="p1-empty.png")
    pg.click("#v-capital .es button"); print("after see open:",pg.evaluate("document.querySelectorAll('#v-capital .rd').length"))
    pg.click("#v-capital .rd[data-deal=zuri]"); pg.wait_for_timeout(700); print("zuri:",pg.inner_text("#v-deal h1"),"|",pg.inner_text("#v-deal .big")); pg.screenshot(path="p1-deal-zuri.png")
    pg.click("#v-deal .back"); ov("landing again")
    pg.click("#v-capital .pf"); ov("portfolio link")
    # other entry points
    pg.click("#nav [data-go=home]"); pg.click("#v-home .it >> nth=0"); pg.wait_for_timeout(700); print("home->",pg.inner_text("#v-deal h1"))
    pg.click("#v-deal .back")
    pg.click("#nav [data-go=community]"); pg.click("#v-community .emb"); pg.wait_for_timeout(700); print("community->",pg.inner_text("#v-deal h1")); pg.click("#v-deal .back")
    pg.click("#nav [data-go=explore]"); pg.fill("#v-explore [data-i=q]","freight"); pg.click("#v-explore [data-i=list] a.r[data-deal=kora]"); pg.wait_for_timeout(700); print("explore->",pg.inner_text("#v-deal h1")); pg.click("#v-deal .back")
    # offline error + retry
    ctx.set_offline(True); pg.click("#nav [data-go=capital]"); pg.wait_for_timeout(200)
    print("offline state:",pg.inner_text("#v-capital .es h3")); pg.screenshot(path="p1-error.png")
    ctx.set_offline(False); pg.wait_for_timeout(900); print("auto-recovered rows:",pg.evaluate("document.querySelectorAll('#v-capital .rd').length"))
    ctx.set_offline(True); pg.click("#v-capital .bell"); pg.wait_for_timeout(200); print("notifs offline:",pg.inner_text("#v-notifs .es h3"))
    ctx.set_offline(False); pg.click("#v-notifs [data-act=retry]"); pg.wait_for_timeout(700); print("notifs retry rows:",pg.evaluate("document.querySelectorAll('#v-notifs .nr').length"))
    # dark
    pg.emulate_media(color_scheme="dark"); pg.wait_for_timeout(150); pg.screenshot(path="p1-capital-dark.png")
    print("ERRORS:",errs)
    b.close()
